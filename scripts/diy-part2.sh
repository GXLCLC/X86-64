#!/bin/bash
# ==============================================================================
# diy-part2.sh —— 编译前自定义脚本（第二部分）
# ------------------------------------------------------------------------------
# 运行时机：在 ./scripts/feeds update -a 与 ./scripts/feeds install -a
#           【之后】、make defconfig 之前执行（由工作流调用）
# 运行目录：OpenWrt/LEDE 源码根目录（工作流中先 cd openwrt 再执行本脚本）
# 主要作用：修改源码/feeds 中的默认设置。
#   1. 把 LuCI 默认主题从 bootstrap 替换为 Argon（随 luci 默认安装）；
#      运行期默认主题另外由 files/etc/uci-defaults/99-custom-settings 兜底设置，
#      两处配合确保刷完机即是 Argon 主题。
#   2. 预留位置：需要给源码打补丁/修改默认 IP 等操作可在此追加。
# ==============================================================================

set -e  # 任何命令失败立即终止

# ------------------------------------------------------------------------------
# 0. 目录自检：确保脚本运行在 OpenWrt 源码根目录
# ------------------------------------------------------------------------------
if [ ! -f rules.mk ] || [ ! -d package ]; then
    echo "[错误] 请在 OpenWrt/LEDE 源码根目录下运行本脚本！"
    exit 1
fi

# ------------------------------------------------------------------------------
# 1. 替换 LuCI 默认主题为 Argon
#    原理：LuCI 集合包（luci / luci-ssl 等）的 Makefile 中通过
#          "+luci-theme-bootstrap" 依赖默认主题。把所有 feeds/luci 下
#          对 luci-theme-bootstrap 的引用替换为 luci-theme-argon，
#          即可让 Argon 跟随 LuCI 默认安装。
#    - grep -rl：递归找出包含该字符串的文件；
#    - xargs -r：没有匹配文件时不执行 sed，避免报错；
#    - || true：不同 LEDE 版本文件位置可能不同，找不到不中断编译，
#      因为 uci-defaults 脚本仍会在首次开机时把主题切成 Argon。
# ------------------------------------------------------------------------------
echo "[diy-part2] 开始替换默认主题为 Argon ..."
grep -rl 'luci-theme-bootstrap' feeds/luci 2>/dev/null \
    | xargs -r sed -i 's/luci-theme-bootstrap/luci-theme-argon/g' \
    && echo "[diy-part2] 已将集合包默认主题依赖替换为 luci-theme-argon" \
    || echo "[diy-part2] 提示：未找到 bootstrap 引用（将由 uci-defaults 设置主题）"

# ------------------------------------------------------------------------------
# 2.（可选）修改默认 LAN IP
#    默认 192.168.1.1 已满足需求，且 LAN IP 由 files/etc/uci-defaults/
#    在首次开机时显式设置，这里不再改动源码。如确需在源码层面修改，
#    可取消下面注释：
# ------------------------------------------------------------------------------
